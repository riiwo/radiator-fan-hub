#!/usr/bin/env python3
# Usage: hex2h.py <env>  - turns attiny/.pio/build/<env>/firmware.hex into ../src/attiny_image.h
import pathlib
import sys

env = sys.argv[1]
here = pathlib.Path(__file__).parent
image = bytearray()
for rec in (here / ".pio" / "build" / env / "firmware.hex").read_text().split():
    raw = bytes.fromhex(rec[1:])
    count, addr, kind, data = raw[0], int.from_bytes(raw[1:3], "big"), raw[3], raw[4:4 + raw[0]]
    if kind == 0:
        image[len(image):addr + count] = bytes(max(0, addr + count - len(image)))
        image[addr:addr + count] = data
if len(image) % 2:
    image.append(0xFF)
rows = [", ".join(f"0x{b:02X}" for b in image[i:i + 16]) for i in range(0, len(image), 16)]
out = here.parent / "src" / "attiny_image.h"
out.write_text(
    f"// Generated by attiny/hex2h.py from {env}\n"
    "#pragma once\n"
    "#include <stdint.h>\n"
    f'static const char attiny_image_name[] = "{env}";\n'
    "static const uint8_t attiny_image[] = {\n  " + ",\n  ".join(rows) + "\n};\n"
)
print(f"{out}: {env}, {len(image)} bytes")
